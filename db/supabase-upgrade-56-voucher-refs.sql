-- ---------------------------------------------------------------------------
-- 1) الخانتان
-- ---------------------------------------------------------------------------
alter table public.vouchers add column if not exists ref_type text;
alter table public.vouchers add column if not exists ref_id   text;

comment on column public.vouchers.ref_type is
  'وسم نوع السند (بناء 184) — مثال: «تحويل بين الحسابات» / «وردية فتح» / «وردية تسوية»؛ فاضي = سند عادي';
comment on column public.vouchers.ref_id is
  'مفتاح ربط السند بمجموعته (بناء 184) — مثال: TFV:<id سند الصرف> لسندَي التحويل؛ فاضي = سند عادي';

-- ---------------------------------------------------------------------------
-- 2) فهرس خفيف للبحث بالمفتاح/النوع داخل الشركة
-- ---------------------------------------------------------------------------
create index if not exists idx_vouchers_org_ref on public.vouchers (org_id, ref_id);

-- ---------------------------------------------------------------------------
-- 3) فحص ذاتي: الخانتان والفهرس موجودين — وإلا فشل ظاهر
-- ---------------------------------------------------------------------------
do $$
declare n int;
begin
  select count(*) into n from information_schema.columns
   where table_schema='public' and table_name='vouchers' and column_name in ('ref_type','ref_id');
  if n < 2 then
    raise exception 'ترحيل ٥٦ فشل: أعمدة ref_type/ref_id لم تُضَاف (وجدت %)', n;
  end if;
  if not exists (select 1 from pg_indexes where schemaname='public' and indexname='idx_vouchers_org_ref') then
    raise exception 'ترحيل ٥٦ فشل: فهرس idx_vouchers_org_ref غير موجود';
  end if;
  raise notice 'ترحيل ٥٦: vouchers.ref_type/ref_id + الفهرس جاهزين ✓';
end $$;

-- ---------------------------------------------------------------------------
-- 4) عرض تنويري
-- ---------------------------------------------------------------------------
select column_name, data_type, is_nullable
  from information_schema.columns
 where table_schema='public' and table_name='vouchers'
   and column_name in ('ref_type','ref_id')
 order by column_name;
